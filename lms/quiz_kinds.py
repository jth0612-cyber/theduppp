def make_sort(topic):
    prompt, bins, pool, exp = _rng.choice(SORT[topic])
    n = min(len(pool), 6 if len(bins) <= 2 else 7)
    for _ in range(30):                                 # 칸마다 하나 이상 들어가게
        pick = _rng.sample(pool, n)
        if {b for _, b in pick} == set(range(len(bins))):
            break
    return {"kind": "sort", "question": prompt, "bins": bins, "items": [x for x, _ in pick],
            "answer_list": [b for _, b in pick], "explanation": exp}


def make_order(topic):
    prompt, seq, exp, n = _rng.choice(ORDER[topic])
    if n and n < len(seq):
        keep = sorted(_rng.sample(range(len(seq)), n))
        seq = [seq[i] for i in keep]
    shown = list(seq)
    while shown == seq:
        _rng.shuffle(shown)
    return {"kind": "order", "question": prompt, "items": shown, "answer_list": [shown.index(x) for x in seq],
            "explanation": exp, "answer_text": " → ".join(seq)}


def make_fill(topic):
    before, after, choices, ans, exp = _rng.choice(FILL[topic])
    order = list(range(4)); _rng.shuffle(order)
    return {"kind": "fill", "question": before + " ___" + after,
            "choices": [choices[i] for i in order], "answer_index": order.index(ans), "explanation": exp}


def make_num(topic):
    q, val, unit, exp = NUM[topic]()
    return {"kind": "num", "question": q, "unit": unit, "answer_num": float(val), "answer_text": f"{_fmt(val)} {unit}",
            "explanation": exp}


def specials(topic):
    """이 단원에서 낼 수 있는 특별 형식 목록."""
    out = []
    if topic in SORT:
        out.append(make_sort)
    if topic in ORDER:
        out.append(make_order)
    if topic in NUM:
        out.append(make_num)
    return out
