def score(form):
    """폼 값(q0..q11 = 'a' 또는 'b')으로 축별 결과 코드를 만든다. 빠진 문항이 있으면 None."""
    picks = []
    for i in range(len(QUESTIONS)):
        v = form.get(f"q{i}")
        if v not in ("a", "b"):
            return None, None
        picks.append(v)
    code = ""
    for key, left, right, _l, _r in AXES:
        a = sum(1 for (axis, *_), p in zip(QUESTIONS, picks) if axis == key and p == "a")
        b = sum(1 for (axis, *_), p in zip(QUESTIONS, picks) if axis == key and p == "b")
        code += left if a >= b else right
    return code, "".join(picks)


def describe(code):
    if not code or len(code) != 4:
        return None
    name, line = TYPE_NAMES[code[:2]]
    axes = []
    for (key, left, right, lname, rname), ch in zip(AXES, code):
        axes.append({"key": key, "letter": ch, "name": lname if ch == left else rname,
                     "other": rname if ch == left else lname, "tips": POLE_TIPS[ch]})
    units = [{"name": n, "common": common, "how": s_tip if code[0] == "S" else p_tip}
             for n, common, s_tip, p_tip in UNITS]
    return {"code": code, "name": name, "line": line, "axes": axes, "units": units}
