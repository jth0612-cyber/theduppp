def info_rows(items):
    """문항정보 시트 줄: 문항번호, 정답, 배점, 단원, 핵심개념, 요구역량, 난이도, 문항형식, 선지구성, 보기함정, 선지분석"""
    out = []
    for no, (ans, pts, unit, concept, skill, level, opts, bogi) in enumerate(items, 1):
        if opts:
            groups = opts.split("|")
            opt_s = " ".join(f"{CIRC[i]}{','.join(g)}" for i, g in enumerate(groups))
            traps = " / ".join(f"{lab}({'O' if t else 'X'}): {why}, {'옳은 진술을 틀렸다고' if t else '틀린 진술을 옳다고'} 판단한 경우입니다. [{tp}]"
                               for lab, (t, why, tp) in zip("ㄱㄴㄷ", bogi))
            out.append([no, ans, pts, unit, concept, skill, level, "합답형", opt_s, traps, None])
        else:
            dis = " / ".join(f"{k}번: {d}({tp})" for k, (d, tp) in sorted(bogi.items()))
            out.append([no, ans, pts, unit, concept, skill, level, "일반", None, None, dis or None])
    return out


def near_wrong(items):
    """문항마다 학생이 많이 고를 오답: 정답과 보기 하나만 다른 선지 (일반형은 선지분석에 있는 선지)."""
    out = []
    for ans, _, _, _, _, _, opts, bogi in items:
        if ans in ("*", "-"):
            out.append([])
        elif opts:
            g = [set(x) for x in opts.split("|")]
            right = g[ans - 1]
            out.append([i + 1 for i, s in enumerate(g) if i + 1 != ans and len(s ^ right) == 1])
        else:
            out.append(sorted(bogi))
    return out


