import random

_rng = random.SystemRandom()


def _josa(word, pair):
    """받침에 맞는 조사: _josa("산소", "이가") → "산소가"."""
    has = (ord(word[-1]) - 0xAC00) % 28 != 0 if "가" <= word[-1] <= "힣" else False
    return word + (pair[0] if has else pair[1])


def _fmt(x):
    return str(int(x)) if float(x).is_integer() else f"{x:g}"


