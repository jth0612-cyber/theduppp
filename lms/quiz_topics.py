def _n01():
    k = _rng.choice(["kmh", "prefix", "charge"])
    if k == "kmh":
        v = _rng.choice([36, 54, 72, 90, 108])
        return (f"{v} km/h는 몇 m/s일까요?", v / 3.6, "m/s", f"1 km/h = 1000 m ÷ 3600 s 이므로 {v} ÷ 3.6 = {_fmt(v / 3.6)} m/s예요.")
