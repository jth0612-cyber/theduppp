def _n32():
    if _rng.random() < 0.5:
        e_in, pct = _rng.choice([(200, 75), (400, 25), (500, 40), (1000, 30), (800, 25)])
        out = e_in * pct // 100
        return (f"{e_in} J의 전기 에너지를 공급해 {out} J를 쓸모 있는 에너지로 얻었어요. 에너지 효율은 몇 %일까요?", pct, "%",
                f"효율 = 유용한 에너지 ÷ 공급한 에너지 × 100 = {out} ÷ {e_in} × 100 = {pct}%.")
    e_in, pct = _rng.choice([(2000, 25), (1000, 30), (4000, 40), (500, 20)])
    lost = e_in * (100 - pct) // 100
