def _n24():
    h = _rng.choice([3, 4, 5, 6])
    oh = _rng.choice([x for x in (2, 3, 4, 5) if x != h])
    w = min(h, oh)
    if _rng.random() < 0.5:
        return (f"H⁺이 {h}개 든 묽은 염산에 OH⁻이 {oh}개 든 수산화 나트륨 수용액을 섞었어요. 생성된 물 분자는 몇 개일까요?", w, "개",
                f"H⁺과 OH⁻은 1 : 1로 반응해요. 둘 중 적은 쪽인 {w}개만큼 물이 생겨요.")
    left = h + h + oh + oh - 2 * w
    return (f"H⁺과 Cl⁻이 {h}개씩 든 묽은 염산에 Na⁺과 OH⁻이 {oh}개씩 든 수용액을 섞었어요. 혼합 용액 속 이온은 모두 몇 개일까요?", left, "개",
            f"Na⁺ {oh}개와 Cl⁻ {h}개는 반응하지 않고 그대로 남아요. H⁺·OH⁻ 중 {w}개씩 물이 되고 나머지 {abs(h - oh)}개가 남아 모두 {left}개예요.")


