def generate_nickname(is_taken):
    """is_taken(nick) -> bool. 조합(2500개)이 겹치면 다시 뽑고, 거의 다 찼으면 숫자를 붙인다."""
    for _ in range(200):
        nick = f"{secrets.choice(MODIFIERS)} {secrets.choice(ANIMALS)}"
        if not is_taken(nick):
            return nick
    while True:
        nick = f"{secrets.choice(MODIFIERS)} {secrets.choice(ANIMALS)} {secrets.randbelow(900) + 100}"
        if not is_taken(nick):
            return nick
