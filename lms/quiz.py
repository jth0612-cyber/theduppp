def bank_quiz(topic_key, count=5):
    items = list(BANK[topic_key])
    _rng.shuffle(items)
    out = []
    for q, choices, ans, exp in items[:count]:
        order = list(range(4))
        _rng.shuffle(order)
        out.append({"question": q, "choices": [choices[i] for i in order],
                    "answer_index": order.index(ans), "explanation": exp})
    return out
